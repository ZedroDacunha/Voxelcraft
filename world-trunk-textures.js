const wrap = n => ((n % 32) + 32) % 32;
export function trunkBarkPixel(x, y) {
    const px = wrap(x), py = wrap(y), mark = bark[py][px];
    return mark === '.' ? BALANCED_TREE_TEXTURES.wood(px, py) : palette[mark];
}
export function trunkEndPixel(x, y) {
    const px = wrap(x), py = wrap(y), mark = end[py][px];
    return mark === '.' ? BALANCED_TREE_TEXTURES.woodEnd(px, py) : palette[mark];
}
